"""`just ddl` (contracts §1): `data/inventory.yaml` → `data/ddl/schema.sql`, `indexes.sql` and `views/grants.sql`.

- **`schema.sql`** — the schema `hartland` with the data licence as its comment (in Czech, so every dump carries it;
  `LICENSE-DATA.md` §2), the tables in `load_order` with their primary keys, unique keys, a CHECK per coded column
  and their foreign keys `DEFERRABLE INITIALLY DEFERRED` (a load copies in any order inside one transaction), then
  the views from `data/ddl/views/<name>.sql` — the materialized ones `WITH NO DATA`, refreshed by `load-world`.
- **`indexes.sql`** — the inventory's indexes, applied after the load (G5 S5.1).
- **`views/grants.sql`** — the roles' rights (contracts §8), applied by `load-world`: the owner role owns, the readonly
  role reads everything, the DocWH loader reads everything but `document.sender_customer_id` — the ground truth the
  pipeline is scored against (contracts §5). Postgres cannot revoke one column of a table-wide grant, so the loader
  gets `document` column by column. The roles exist on the cluster (olymp); this file grants, never creates.

The three files are generated and committed; `--check` (CI) fails when a committed file differs from the render.
The view files are hand-written SELECTs, read by the render, not written by it.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from pathlib import Path

from hartland_sim.config import DATA_DIR, Column, InventoryConfig, Table

DDL_DIR = DATA_DIR / "ddl"

GENERATED = ("schema.sql", "indexes.sql", "views/grants.sql")

OWNER = "hartland_owner"
READONLY = "hartland_readonly"
DOCWH = "hartland_docwh"
HIDDEN_FROM_DOCWH = ("document", "sender_customer_id")

# LICENSE-DATA.md §2, in Czech (NH-D8): the comment on the schema.
LICENCE_NOTICE = (
    "Databáze New Hartland je zpřístupněna pod licencí Open Database License 1.0: "
    "https://opendatacommons.org/licenses/odbl/1-0/. Práva k jednotlivému obsahu databáze jsou licencována pod "
    "licencí Database Contents License 1.0: https://opendatacommons.org/licenses/dbcl/1-0/. Obsahuje údaje "
    "z OpenStreetMap, © přispěvatelé OpenStreetMap, dostupné pod licencí ODbL."
)

_HEADER = (
    "-- Generated by `just ddl` from data/inventory.yaml (contracts §1). Do not edit: edit the inventory, re-render."
)


def render(inventory: InventoryConfig, ddl_dir: Path = DDL_DIR) -> dict[str, str]:
    """The generated files by their path under `ddl_dir`; the view SQL is read from `ddl_dir/views/`."""
    return {
        "schema.sql": _schema(inventory, ddl_dir),
        "indexes.sql": _indexes(inventory),
        "views/grants.sql": _grants(inventory),
    }


def write(inventory: InventoryConfig, ddl_dir: Path = DDL_DIR) -> list[str]:
    """Render into `ddl_dir`; the files that changed."""
    changed = []
    for name, text in render(inventory, ddl_dir).items():
        path = ddl_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            changed.append(name)
    return changed


def drift(inventory: InventoryConfig, ddl_dir: Path = DDL_DIR) -> list[str]:
    """The committed files that differ from the render (or are missing), each as a problem line."""
    problems = []
    for name, text in render(inventory, ddl_dir).items():
        path = ddl_dir / name
        if not path.exists():
            problems.append(f"data/ddl/{name}: missing")
        elif path.read_text(encoding="utf-8") != text:
            problems.append(f"data/ddl/{name}: differs from the render of data/inventory.yaml")
    return problems


def literal(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


# ── schema.sql ───────────────────────────────────────────────────────────────


def _schema(inventory: InventoryConfig, ddl_dir: Path) -> str:
    schema = inventory.schema
    parts = [
        _HEADER,
        "",
        f"CREATE SCHEMA {schema};",
        f"COMMENT ON SCHEMA {schema} IS {literal(LICENCE_NOTICE)};",
    ]
    group = None
    for table in inventory.tables:
        if table.group != group:
            group = table.group
            parts += ["", f"-- ── {group} " + "─" * max(0, 100 - len(group))]
        parts += ["", _create_table(schema, table, inventory.codes)]
    parts += ["", "-- ── views " + "─" * 95, "", f"SET search_path TO {schema};"]
    for view in inventory.views:
        body = (ddl_dir / view.sql_file).read_text(encoding="utf-8").rstrip()
        if view.kind == "materialized_view":
            parts += ["", f"CREATE MATERIALIZED VIEW {schema}.{view.name} AS", body, "WITH NO DATA;"]
        else:
            parts += ["", f"CREATE VIEW {schema}.{view.name} AS", body + ";"]
    parts += ["", "RESET search_path;"]
    return "\n".join(parts) + "\n"


def _create_table(schema: str, table: Table, codes: Mapping[str, Mapping[str, str]]) -> str:
    lines = [_column(column, codes) for column in table.columns]
    lines.append(f"CONSTRAINT {table.name}_pkey PRIMARY KEY ({', '.join(table.pk)})")
    for key in table.unique:
        lines.append(f"CONSTRAINT {_name(table.name, key, 'key')} UNIQUE ({', '.join(key)})")
    for fk in table.fks:
        lines.append(
            f"CONSTRAINT {_name(table.name, [fk.column], 'fkey')} FOREIGN KEY ({fk.column})"
            f" REFERENCES {schema}.{fk.table} ({fk.target}) DEFERRABLE INITIALLY DEFERRED"
        )
    body = ",\n".join(f"    {line}" for line in lines)
    return f"CREATE TABLE {schema}.{table.name} (\n{body}\n);"


def _column(column: Column, codes: Mapping[str, Mapping[str, str]]) -> str:
    text = f"{column.name} {column.type}"
    if not column.nullable:
        text += " NOT NULL"
    if column.coded is not None:
        values = ", ".join(literal(value) for value in codes[column.coded])
        text += f" CHECK ({column.name} IN ({values}))"
    return text


def _name(table: str, columns: Iterable[str], suffix: str) -> str:
    name = "_".join([table, *columns, suffix])
    if len(name) > 63:  # Postgres truncates identifiers at 63 bytes; two long names could then collide
        raise ValueError(f"{name}: longer than Postgres's 63 bytes — shorten a column name")
    return name


# ── indexes.sql ──────────────────────────────────────────────────────────────


def _indexes(inventory: InventoryConfig) -> str:
    parts = [_HEADER, "-- Applied after the load (G5 S5.1).", ""]
    for table in inventory.tables:
        for key in table.indexes:
            parts.append(
                f"CREATE INDEX {_name(table.name, key, 'idx')} ON {inventory.schema}.{table.name} ({', '.join(key)});"
            )
    return "\n".join(parts) + "\n"


# ── views/grants.sql ─────────────────────────────────────────────────────────


def _grants(inventory: InventoryConfig) -> str:
    schema = inventory.schema
    hidden_table, hidden_column = HIDDEN_FROM_DOCWH
    others = [table.name for table in inventory.tables if table.name != hidden_table]
    others += [view.name for view in inventory.views]
    visible = [column.name for column in inventory.table(hidden_table).columns if column.name != hidden_column]
    lines = [
        _HEADER,
        f"-- The roles of contracts §8, applied by `load-world` as {OWNER}; they exist on the cluster.",
        f"-- {DOCWH} reads everything but {hidden_table}.{hidden_column} (contracts §5),",
        f"-- so it gets {hidden_table} column by column.",
        "",
        f"GRANT USAGE ON SCHEMA {schema} TO {READONLY}, {DOCWH};",
        f"GRANT SELECT ON ALL TABLES IN SCHEMA {schema} TO {READONLY};",
        f"REVOKE ALL ON ALL TABLES IN SCHEMA {schema} FROM {DOCWH};",
    ]
    lines += [f"GRANT SELECT ON {schema}.{name} TO {DOCWH};" for name in others]
    lines.append(f"GRANT SELECT ({', '.join(visible)}) ON {schema}.{hidden_table} TO {DOCWH};")
    return "\n".join(lines) + "\n"
